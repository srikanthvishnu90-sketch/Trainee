// R10 WO-H fix 14: the company interview brief File, opened in Chromium the way quality.ts opens the market briefs: the File
// service's own validation and renderer inside the trainee-file shell, at 390 px (phone) and 1280 px (desktop), light,
// deviceScaleFactor 2. Three Files from the spec's turns over the synthetic company web (tests/helpers/research_company_web.ts):
// the overview while the role is unknown, the full brief with the role, and the "less generic" questions only. Scored on
// quality.ts's layout and readability lines (R4: no sideways scroll, nothing past the card, no empty section; R5: fact text at least
// 16 px, nothing under 13 px, WCAG AA, taps at least 44 px). $0: no model, no network.
//   deno run -A --no-check evals/career/research-free/company_shots.ts
// deno-lint-ignore-file no-explicit-any
import { researchCompany } from "../../../supabase/functions/_shared/agent/research/company.ts";
import { bodyHtml, type FileRecord, KIND_CSS, validateKind } from "../../../supabase/functions/_shared/file_kinds.ts";
import { fileShellHtml } from "../../../supabase/functions/_shared/file_design.ts";
import { layout } from "../../../supabase/functions/_shared/file_page.ts";
import { NOW, world } from "../../../tests/helpers/research_company_web.ts";
import { browserChecks, MEASURE, playwright } from "./quality.ts";

const ROOT = new URL("../../../", import.meta.url).pathname;
const OUT = `${ROOT}tests/architect/snapshots/research-company`;
const RUNS: { id: string; role: string | null; focus: "all" | "questions"; audience: string | null; question: string }[] = [
  { id: "CO-1-overview", role: null, focus: "all", audience: null, question: "Research Stripe before my interview. I want the company, business model, recent developments and what I should ask." },
  { id: "CO-2-role", role: "Data analyst internship", focus: "all", audience: null, question: "Data analyst internship." },
  { id: "CO-3-questions", role: "Data analyst internship", focus: "questions", audience: "hiring manager", question: "Less generic, what should I ask the hiring manager?" },
];

if (import.meta.main) {
  const pw = playwright();
  if (!pw) { console.error("no Playwright"); Deno.exit(2); }
  await Deno.mkdir(OUT, { recursive: true });
  const browser = await pw.chromium.launch({ headless: true, args: Deno.uid?.() === 0 ? ["--no-sandbox"] : [] });
  const lines: string[] = [];
  let pass = 0;
  try {
    for (const r of RUNS) {
      const w = world();
      await researchCompany({ company: "Stripe", role: r.role, question: r.question, focus: r.focus, audience: r.audience, now: NOW, deps: w.deps, plan: { queries: ["Stripe"], companies: ["Stripe"], sites: ["stripe.example"] } });
      const v: any = validateKind("research_brief", w.published[0], { now: NOW });
      if (!v.ok) { lines.push(`FAIL ${r.id}: the File does not validate: ${v.errors.join("; ")}`); continue; }
      const rec = { id: r.id, userId: "u", kind: "research_brief", data: v.data, state: {}, tag: null, created_at: NOW, expires_at: NOW + 86400_000, revoked_at: null } as FileRecord;
      const html = layout(`${v.data.title} - Trainee`, `<div id="root">${fileShellHtml({ made: "Made for you · Nov 9, 2026", eyebrow: "Research brief", title: v.data.title, stamp: "Sources read Nov 9, 2026", body: bodyHtml(rec, "fs1." + "a".repeat(64)) })}</div>`, { css: KIND_CSS });
      const fails: string[] = [];
      for (const width of [390, 1280]) {
        const ctx = await browser.newContext({ viewport: { width, height: 900 }, colorScheme: "light", deviceScaleFactor: 2, reducedMotion: "reduce" });
        await ctx.route("**/*", (x: any) => x.abort());
        const pg = await ctx.newPage();
        await pg.setContent(html, { waitUntil: "load" });
        const c = browserChecks(await pg.evaluate(MEASURE), width);
        fails.push(...c.r4.map((x) => `R4 ${width}: ${x}`), ...c.r5.map((x) => `R5 ${width}: ${x}`));
        await Deno.writeFile(`${OUT}/${r.id}-${width}.png`, new Uint8Array(await pg.screenshot({ fullPage: true, animations: "disabled" })));
        await ctx.close();
      }
      if (!fails.length) pass++;
      lines.push(`${fails.length ? "FAIL" : "PASS"} ${r.id}: ${v.data.sources.length} sources; shots ${r.id}-390.png, ${r.id}-1280.png${fails.length ? `; ${[...new Set(fails)].join(" | ")}` : ""}`);
    }
  } finally { await browser.close(); }
  for (const l of lines) console.log(l);
  console.log(`\nlayout and readability (R4, R5): ${pass}/${RUNS.length}`);
  await Deno.writeTextFile(`${OUT}/REPORT.md`, `# Company interview brief: phone and desktop\n\nGenerated by \`deno run -A --no-check evals/career/research-free/company_shots.ts\` (synthetic web, no model, $0), 390 px and 1280 px, light, deviceScaleFactor 2.\n\n${lines.map((l) => `- ${l}`).join("\n")}\n\nlayout and readability (R4, R5): ${pass}/${RUNS.length}\n`);
}
