#!/usr/bin/env python3
"""Writes supabase/functions/_shared/career_resume_metrics.ts: the advance widths of the four standard PDF faces the resume
templates use, for every character the PDF writer can encode. Source: Adobe's Core 14 AFM metrics as shipped in pdfminer.six
(pdfminer/fontmetrics.py). Run: python3 scripts/resume-metrics.py  (add --check to fail when the file is stale)."""
import json, sys
from pdfminer.fontmetrics import FONT_METRICS

EXTRAS = "€…‘’“”•–—˜™œŸ"
CHARS = "".join(chr(c) for c in range(32, 127)) + "".join(chr(c) for c in range(160, 256)) + EXTRAS
FACES = ["Helvetica", "Helvetica-Bold", "Times-Roman", "Times-Bold"]

def build():
    widths = {}
    for face in FACES:
        desc, w = FONT_METRICS[face]
        row = []
        for ch in CHARS:
            # The AFMs have no glyph for the no-break space or the soft hyphen: they take the space's and the hyphen's widths.
            # The euro sign is not in these AFMs; Adobe's later Core 14 AFMs give it 556 (Helvetica) and 500 (Times).
            v = w.get(ch, w.get({"\u00a0": " ", "\u00ad": "-"}.get(ch, ""), None))
            if v is None and ch == "\u20ac":
                v = 556 if face.startswith("Helvetica") else 500
            if v is None:
                raise SystemExit(f"{face} has no width for U+{ord(ch):04X}")
            row.append(int(v))
        widths[face] = {"ascent": int(desc["Ascent"]), "descent": int(desc["Descent"]), "capHeight": int(desc["CapHeight"]), "w": row}
    lines = [
        "// GENERATED by scripts/resume-metrics.py (do not edit): advance widths, 1/1000 em, of the four standard PDF faces the",
        "// resume templates set text in, for every character the PDF writer can encode (router_core encodeWinAnsi: ASCII 32-126,",
        "// Latin-1 160-255 and its 13 extras). Source: Adobe's Core 14 AFM metrics as shipped in pdfminer.six (fontmetrics.py).",
        "// Arial and Times New Roman, the faces the DOCX names, are metric-compatible with Helvetica and Times.",
        f"export const ENCODABLE = {json.dumps(CHARS)};",
        "export type Face = " + " | ".join(json.dumps(f) for f in FACES) + ";",
        "export const METRICS: Record<Face, { ascent: number; descent: number; capHeight: number; w: number[] }> = {",
    ]
    for face in FACES:
        lines.append(f"  {json.dumps(face)}: {json.dumps(widths[face], separators=(',', ':'))},")
    lines.append("};")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    path = "supabase/functions/_shared/career_resume_metrics.ts"
    text = build()
    if "--check" in sys.argv:
        if open(path, encoding="utf8").read() != text:
            raise SystemExit(f"{path} is stale; run python3 scripts/resume-metrics.py")
        print("metrics current")
    else:
        open(path, "w", encoding="utf8").write(text)
        print(f"wrote {path}")
